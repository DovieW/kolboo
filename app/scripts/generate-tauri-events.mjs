import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDir, "..");

const rustEventsPath = path.join(appRoot, "src-tauri", "src", "events.rs");
const outPath = path.join(appRoot, "src", "lib", "tauri", "events.generated.ts");

if (!fs.existsSync(rustEventsPath)) {
	throw new Error(`Rust events file not found: ${rustEventsPath}`);
}

const source = fs.readFileSync(rustEventsPath, "utf8").replace(/^\uFEFF/, "");

// Match: pub const EVENT_FOO: &str = "some-event";
const constRegex =
	/\bpub\s+const\s+[A-Z0-9_]+\s*:\s*&str\s*=\s*"([^"]+)"\s*;/g;

const namesInOrder = [];
const seen = new Set();

for (const match of source.matchAll(constRegex)) {
	const name = match[1];
	if (!name) continue;
	if (seen.has(name)) {
		throw new Error(`Duplicate backend event name in events.rs: ${name}`);
	}
	seen.add(name);
	namesInOrder.push(name);
}

if (namesInOrder.length === 0) {
	throw new Error(
		`No event constants found in ${rustEventsPath}. Expected pub const ...: &str = "...";`,
	);
}

const header = `// This file is generated by scripts/generate-tauri-events.mjs
//
// Source of truth: src-tauri/src/events.rs
//
// Do not edit by hand.
`;

const lines = [];
lines.push(header.trimEnd());
lines.push("");
lines.push("export const BACKEND_EVENT_NAMES = [");
for (const n of namesInOrder) {
	lines.push(`\t${JSON.stringify(n)},`);
}
lines.push("] as const;");
lines.push("");
lines.push("export type BackendEventName = (typeof BACKEND_EVENT_NAMES)[number];");
lines.push("");

const content = `${lines.join("\n")}\n`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content, "utf8");

console.log(`Generated ${namesInOrder.length} backend event names -> ${outPath}`);
