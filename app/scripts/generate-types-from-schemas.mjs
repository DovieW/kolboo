import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDir, "..");

const schemasDir = path.join(appRoot, "src-tauri", "gen", "schemas");
const outPath = path.join(appRoot, "src", "lib", "tauri", "types.generated.ts");

if (!fs.existsSync(schemasDir)) {
	throw new Error(`Schemas directory not found: ${schemasDir}`);
}

const schemaFiles = fs
	.readdirSync(schemasDir)
	.filter((name) => name.endsWith(".schema.json"))
	.sort();

if (schemaFiles.length === 0) {
	throw new Error(`No schema files found in ${schemasDir}`);
}

const header = `// This file is generated by scripts/generate-types-from-schemas.mjs
//
// Source of truth: src-tauri/gen/schemas/*.schema.json
//
// Do not edit by hand.
`;

// Track already emitted type names to avoid duplicates
const emittedTypes = new Set();
const typeBlocks = [];

for (const file of schemaFiles) {
	const filePath = path.join(schemasDir, file);
	const schemaText = fs.readFileSync(filePath, "utf8");

	let schema;
	try {
		schema = JSON.parse(schemaText);
	} catch {
		console.warn(`Skipping ${file}: invalid JSON`);
		continue;
	}

	// Skip non-object schemas (e.g., simple string enums might not have a useful type)
	if (!schema.title) {
		console.warn(`Skipping ${file}: no title`);
		continue;
	}

	try {
		const ts = await compile(schema, schema.title, {
			bannerComment: "",
			additionalProperties: false,
			unknownAny: false,
			strictIndexSignatures: true,
		});

		// Filter out already emitted types to avoid duplicates
		const lines = ts.split("\n");
		const filteredLines = [];
		let skipUntilNextExport = false;
		let currentTypeName = null;

		for (const line of lines) {
			// Detect export interface/type declarations
			const interfaceMatch = line.match(/^export interface (\w+)/);
			const typeMatch = line.match(/^export type (\w+)/);

			if (interfaceMatch || typeMatch) {
				currentTypeName = (interfaceMatch || typeMatch)[1];
				if (emittedTypes.has(currentTypeName)) {
					skipUntilNextExport = true;
					continue;
				}
				emittedTypes.add(currentTypeName);
				skipUntilNextExport = false;
			}

			if (skipUntilNextExport) {
				// Keep skipping until we hit the next export or end of block
				if (
					line.startsWith("export ") ||
					(line === "}" && !line.includes("{"))
				) {
					// Check if this is a new export
					const nextInterface = line.match(/^export interface (\w+)/);
					const nextType = line.match(/^export type (\w+)/);
					if (nextInterface || nextType) {
						currentTypeName = (nextInterface || nextType)[1];
						if (emittedTypes.has(currentTypeName)) {
							continue;
						}
						emittedTypes.add(currentTypeName);
						skipUntilNextExport = false;
						filteredLines.push(line);
					} else if (line === "}") {
						// End of skipped interface
						continue;
					}
				}
				continue;
			}

			filteredLines.push(line);
		}

		const filtered = filteredLines.join("\n").trim();
		if (filtered) {
			typeBlocks.push(`// From: ${file}\n${filtered}`);
		}
	} catch (e) {
		console.warn(`Skipping ${file}: ${e.message}`);
	}
}

const content = `${header}\n${typeBlocks.join("\n\n")}\n`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content, "utf8");

console.log(
	`Generated ${typeBlocks.length} types from ${schemaFiles.length} schemas -> ${outPath}`,
);
